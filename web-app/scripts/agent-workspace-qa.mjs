import {chromium} from "playwright";
import AxeBuilder from "@axe-core/playwright";
import {spawn} from "node:child_process";
import {mkdir,writeFile} from "node:fs/promises";
import assert from "node:assert/strict";
import {setTimeout as delay} from "node:timers/promises";
await mkdir("artifacts/agents",{recursive:true});
const server=spawn(process.execPath,["node_modules/next/dist/bin/next","start","-p","3000"],{stdio:["ignore","pipe","pipe"]});
let logs="";server.stdout.on("data",data=>logs+=data);server.stderr.on("data",data=>logs+=data);
let browser;
const report=[];
try{
 let ready=false;
 for(let i=0;i<60;i++){try{if((await fetch("http://localhost:3000/agents")).ok){ready=true;break;}}catch{}await delay(500);}
 assert(ready,"Next server did not start");
 browser=await chromium.launch({channel:"chrome"});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto("http://localhost:3000/agents");
 await page.getByRole("heading",{name:"A specialist for the work."}).waitFor();
 assert.equal(await page.locator("#agent option").count(),16);
 await page.screenshot({path:"artifacts/agents/desktop.png",fullPage:true});
 const axe=await new AxeBuilder({page}).analyze();
 assert.deepEqual(axe.violations.map(v=>({id:v.id,description:v.description})),[]);
 report.push("Desktop rendering, all role choices and axe accessibility checks passed");
 await page.getByRole("checkbox").check();
 await page.locator("#request").fill("Review a sales pipeline and define data quality checks.");
 await page.locator("#evidence").fill("orders(id integer, amount numeric); 20 rows.");
 await page.getByRole("button",{name:"Run demo workflow"}).click();
 await page.getByRole("heading",{name:"awaiting human",exact:true}).waitFor();
 assert.equal(await page.locator('section[aria-label="Agent result"]').count(),1);
 assert.match(await page.locator('section[aria-label="Agent result"]').innerText(),/Demo result/i);
 const downloadPromise=page.waitForEvent("download");
 await page.getByRole("button",{name:"Download JSON"}).click();
 const download=await downloadPromise;
 assert.match(download.suggestedFilename(),/^agent-result-/);
 await download.saveAs("artifacts/agents/demo-result.json");
 await page.getByRole("button",{name:"Clear result"}).click();
 await page.locator("#agent").selectOption("mid-level-data-engineer");
 await page.getByRole("button",{name:"Run demo workflow"}).click();
 await page.getByRole("heading",{name:"awaiting human",exact:true}).waitFor();
 const result=page.locator('section[aria-label="Agent result"]');
 assert.match(await result.innerText(),/Transformation SQL or code/);
 assert.match(await result.innerText(),/Demo placeholder/);
 assert.equal((await result.locator("ol li").count()),4);
 await page.screenshot({path:"artifacts/agents/specialist-demo.png",fullPage:true});
 const resultAxe=await new AxeBuilder({page}).analyze();
 assert.deepEqual(resultAxe.violations.map(v=>v.id),[]);
 report.push("Real demo API, specialist workflow, review gate, JSON download and clear controls passed");
 await page.getByRole("button",{name:"Clear result"}).click();
 await page.getByRole("checkbox").uncheck();
 await page.locator("#model").fill("test-model");
 await page.locator("#api-key").fill("fake-browser-key-12345");
 let sentKey;
 await page.route("**/api/agents/tasks",async route=>{
  sentKey=route.request().headers()["x-agent-api-key"];
  assert(!route.request().postData().includes("fake-browser-key-12345"));
  await route.fulfill({status:401,contentType:"application/json",body:JSON.stringify({error:"Provider rejected the API key or model access."})});
 });
 await page.getByRole("button",{name:"Run with my key"}).click();
 await page.getByRole("alert").waitFor();
 assert.equal(sentKey,"fake-browser-key-12345");
 assert.equal(await page.locator("#api-key").inputValue(),"");
 assert.deepEqual(await page.evaluate(()=>({local:Object.keys(localStorage),session:Object.keys(sessionStorage)})),{local:[],session:[]});
 report.push("Live-mode request wiring, immediate key clearing, no browser persistence and auth error display passed (mocked endpoint)");
 await page.setViewportSize({width:375,height:812});
 await page.screenshot({path:"artifacts/agents/mobile.png",fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),"Mobile horizontal overflow");
 const mobileAxe=await new AxeBuilder({page}).analyze();
 assert.deepEqual(mobileAxe.violations.map(v=>v.id),[]);
 assert.deepEqual(errors,[]);
 report.push("375px mobile layout, accessibility and browser runtime checks passed");
 await writeFile("artifacts/agents/report.json",JSON.stringify({passed:report},null,2));
 console.log(report.join("\n"));
}finally{
 if(browser)await browser.close();
 server.kill("SIGTERM");
 await writeFile("artifacts/agents/server.log",logs);
}
